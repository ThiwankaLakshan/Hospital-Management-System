// Packs everything in public/ into src/assets.js so the site is served by the Express function itself.
// Run "npm run embed" after you edit any file in public/.
const fs = require('fs'), path = require('path');
const types = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'application/javascript; charset=utf-8' };
const out = {};
for (const f of fs.readdirSync('public')) out[f] = { type: types[path.extname(f)] || 'text/plain', body: fs.readFileSync('public/' + f, 'utf8') };
fs.writeFileSync('src/assets.js', '// GENERATED by scripts/embed.js. Do not edit.\nmodule.exports = ' + JSON.stringify(out) + ';\n');
console.log('Embedded', Object.keys(out).length, 'files');
